<script src="https://checkout.freemius.com/js/v1/"></script>
<script>
    document.addEventListener("DOMContentLoaded", function () {
        // Billing cycle toggle logic
        const billingToggleButtons = document.querySelectorAll(".hf-billing-toggle");
        const priceValues = document.querySelectorAll(".hf-price-value");
        const priceSuffixes = document.querySelectorAll(".hf-price-suffix");
        let activeCycle = "monthly";

        billingToggleButtons.forEach(btn => {
            btn.addEventListener("click", function () {
                // Remove active classes
                billingToggleButtons.forEach(b => b.classList.remove("active", "btn-primary", "bg-primary", "text-white"));
                billingToggleButtons.forEach(b => b.classList.add("bg-white", "text-dark"));

                // Set active states
                this.classList.remove("bg-white", "text-dark");
                this.classList.add("active", "btn-primary", "bg-primary", "text-white");

                activeCycle = this.getAttribute("data-cycle");

                // Update pricing displays
                priceValues.forEach(val => {
                    const price = val.getAttribute(`data-${activeCycle}`);
                    val.textContent = price;
                });

                // Update price suffix display
                priceSuffixes.forEach(suffix => {
                    if (activeCycle === "monthly") {
                        suffix.textContent = "/ month";
                    } else if (activeCycle === "annual") {
                        suffix.textContent = "/ year";
                    } else if (activeCycle === "lifetime") {
                        suffix.textContent = " lifetime";
                    }
                });
            });
        });

        // Initialize Freemius Checkout Handler
        let fsHandler = null;

        // Wait for FS to be loaded in client
        function initFreemius() {
            if (typeof FS === "undefined" || typeof FS.Checkout === "undefined") {
                setTimeout(initFreemius, 100);
                return;
            }

            fsHandler = new FS.Checkout({
                plugin_id: "31302",
                product_id: "31302",
                public_key: "pk_fb1ac589818279dabd61451172db1",
                image: "https://ps.w.org/header-and-footer-script-adder/assets/icon-128x128.png?rev=3564161"
            });
        }

        initFreemius();

        // Bind checkout events to pricing card actions
        const buyButtons = document.querySelectorAll(".hf-buy-btn");
        buyButtons.forEach(btn => {
            btn.addEventListener("click", function (e) {
                e.preventDefault();
                const planId = this.getAttribute("data-plan");
                const planName = this.getAttribute("data-name");
                
                // Retrieve price in handler-wide scope
                const priceCard = this.closest('.hf-pricing-card');
                const priceValueEl = priceCard ? priceCard.querySelector('.hf-price-value') : null;
                const price = priceValueEl ? priceValueEl.getAttribute(`data-${activeCycle}`) : '0.00';

                // Trigger GA4/GTM Event
                if (typeof window.trackGA4Event === 'function') {
                    window.trackGA4Event('click_pricing_cta', {
                        'plan_id': planId,
                        'plan_name': planName,
                        'billing_cycle': activeCycle,
                        'price': parseFloat(price),
                        'currency': 'USD'
                    });
                } else {
                    console.log("GA4 Event Triggered (fallback): click_pricing_cta", {
                        'plan_id': planId,
                        'plan_name': planName,
                        'billing_cycle': activeCycle,
                        'price': parseFloat(price || 0),
                        'currency': 'USD'
                    });
                }

                if (!fsHandler) {
                    // Fallback to direct URL if checkout script failed to configure
                    const fallbackUrl = `https://checkout.freemius.com/product/31302/plan/${planId}/?billing_cycle=${activeCycle}&trial=true`;
                    window.open(fallbackUrl, "_blank");
                    return;
                }

                // Open overlay checkout modal via Freemius Checkout SDK
                fsHandler.open({
                    name: `Header Footer Script Adder Pro - ${planName}`,
                    plan_id: planId,
                    billing_cycle: activeCycle,
                    trial: true,
                    purchaseCompleted: function (response) {
                        console.log("Freemius purchase completed:", response);

                        // Trigger standard GA4/GTM Purchase Conversion Event
                        if (typeof window.trackGA4Event === 'function') {
                            window.trackGA4Event('purchase', {
                                'transaction_id': (response.purchase ? response.purchase.id : 'fs_' + Date.now()),
                                'value': parseFloat(price),
                                'currency': 'USD',
                                'items': [{
                                    'item_id': planId,
                                    'item_name': 'Header Footer Script Adder Pro - ' + planName,
                                    'price': parseFloat(price),
                                    'quantity': 1
                                }]
                            });
                        } else {
                            console.log("GA4 Event Triggered (fallback): purchase", {
                                'transaction_id': (response.purchase ? response.purchase.id : 'fs_' + Date.now()),
                                'value': parseFloat(price),
                                'currency': 'USD',
                                'items': [{
                                    'item_id': planId,
                                    'item_name': 'Header Footer Script Adder Pro - ' + planName,
                                    'price': parseFloat(price),
                                    'quantity': 1
                                }]
                            });
                        }
                        
                        // Redirect to thank you page
                        window.location.href = "{{ route('plugins.header-footer-script-adder.thank-you') }}";
                    },
                    cancel: function() {
                        console.log("Freemius checkout cancelled");
                    }
                });
            });
        });
    });
</script>

